let PRIVATE_KEY_PEM: string;
let PUBLIC_KEY: CryptoKey;

/** PKCS#8 DER as the PEM block a Google service account's `private_key` holds. */
function toPem(der: ArrayBuffer): string {
  const bytes = new Uint8Array(der);
  let binary = "";
  for (const byte of bytes) binary += String.fromCharCode(byte);
  const body = btoa(binary).replace(/(.{64})/g, "$1\n");
  return `-----BEGIN PRIVATE KEY-----\n${body}\n-----END PRIVATE KEY-----\n`;
}

beforeAll(async () => {
  // A REAL key, not a fixture string: importRs256Key() hands the PEM
  // straight to crypto.subtle.importKey, so anything that is not a genuine
  // PKCS#8 RSA key exercises only the error path. 2048 bits is what Google
  // issues, and generating one costs ~50 ms once for the whole file.
  const pair = (await crypto.subtle.generateKey(
    { name: "RSASSA-PKCS1-v1_5", modulusLength: 2048, publicExponent: new Uint8Array([1, 0, 1]), hash: "SHA-256" },
    true,
    ["sign", "verify"],
  )) as CryptoKeyPair;
  // `as ArrayBuffer`: exportKey is typed `ArrayBuffer | JsonWebKey` across
  // both its overloads, and only the "jwk" format returns the second.
  PRIVATE_KEY_PEM = toPem((await crypto.subtle.exportKey("pkcs8", pair.privateKey)) as ArrayBuffer);
  PUBLIC_KEY = pair.publicKey;
});

