describe("when FCM refuses the message", () => {
  // The log carries the status, the need, the topic AND Google's body --
  // all four, because this line is the entire diagnosis available for a
  // notification that nobody received and nothing recorded.
  it("logs the status, the need, the topic and Google's own error body", async () => {
    fcmReply = () =>
      new Response(JSON.stringify({ error: { code: 404, status: "NOT_FOUND", message: "Requested entity was not found." } }), {
        status: 404,
      });

    await expect(notify()).resolves.toBeUndefined();

    expect(consoleError).toHaveBeenCalledWith(
      `notify-need-firebase: FCM 404 for need ${NEED_ID} topic foodbank-${SALISBURY_UUID}: ` +
        '{"error":{"code":404,"status":"NOT_FOUND","message":"Requested entity was not found."}}',
    );
    // Crucially NOT logged as a success: the success line is what an
    // operator greps for, and a failure that also logged one would be
    // indistinguishable from a delivery.
    expect(consoleLog).not.toHaveBeenCalled();
  });

  it("logs and returns when FCM cannot be reached", async () => {
    fcmReply = () => {
      throw new TypeError("Network connection lost.");
    };

    await expect(notify()).resolves.toBeUndefined();

    expect(consoleError).toHaveBeenCalledWith(`notify-need-firebase: send failed for need ${NEED_ID}`, expect.any(TypeError));
    expect(consoleLog).not.toHaveBeenCalled();
  });

  // SUSPECT, pinned as-is. The response body is parsed INSIDE the try, after
  // the ok check has passed, so a 200 whose body is not JSON is reported as
  // "send failed" -- for a message FCM has already accepted and delivered.
  // Nothing re-sends it (the caller acks), so the consequence is a false
  // failure in the log rather than a duplicate notification, but an
  // operator chasing it is chasing a send that worked. Reported, not fixed.
  it("reports a successful send as failed when the 200 body is not JSON", async () => {
    fcmReply = () => new Response("OK", { status: 200 });

    await notify();

    expect(consoleError).toHaveBeenCalledWith(`notify-need-firebase: send failed for need ${NEED_ID}`, expect.any(Error));
    expect(consoleLog).not.toHaveBeenCalled();
  });

  // SUSPECT, pinned as-is, and the worst of the three because it lasts an
  // hour. A 401 means the token is dead -- revoked key, disabled service
  // account -- and nothing invalidates `cachedToken`, so every subsequent
  // message in the isolate presents the SAME dead token and fails
  // identically. No retry, no DLQ, no row: an hour of app notifications
  // vanish leaving only console.error behind. Reported, not fixed.
  it("keeps presenting a token FCM has just rejected as unauthorised", async () => {
    fcmReply = () => new Response(JSON.stringify({ error: { code: 401, status: "UNAUTHENTICATED" } }), { status: 401 });

    await notify(NEED_ID);
    await notify(DECOY_NEED_ID);

    expect(tokenCalls()).toHaveLength(1);
    expect(fcmCalls().map((c) => c.headers.Authorization)).toEqual([`Bearer ${ACCESS_TOKEN}`, `Bearer ${ACCESS_TOKEN}`]);
    expect(consoleError).toHaveBeenCalledTimes(2);
  });
});

