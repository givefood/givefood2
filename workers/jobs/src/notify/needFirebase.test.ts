describe("the FCM v1 message -- notifications.py:238-269's messaging.Message, field for field", () => {
  // toEqual over the WHOLE body, not toMatchObject: an extra, renamed or
  // dropped key is the failure. The notification/data/webpush split is not
  // redundancy -- `notification` is what a native app renders, `webpush`
  // overrides it for FCM's own browser transport, and `data` is what a
  // handler reads programmatically -- so a field lost from one of the three
  // is a channel that silently renders wrong while the other two look fine.
  it("sends the three-way notification/data/webpush message to the food bank's topic", async () => {
    await notify();

    expect(sentMessage()).toEqual({
      message: {
        topic: `foodbank-${SALISBURY_UUID}`,
        notification: { title: "Salisbury needs 3 items", body: "Beans, Pasta, Tinned Tomatoes" },
        data: { foodbank_slug: "salisbury" },
        webpush: {
          notification: {
            title: "Salisbury needs 3 items",
            body: "Beans, Pasta, Tinned Tomatoes",
            // ROOT-RELATIVE, exactly as Django has it (notifications.py:249-250):
            // the service worker resolves it against the page origin, and an
            // absolute URL here breaks the day the site moves domain.
            icon: "/static/img/notificationicon.svg",
            badge: "/static/img/notificationicon.svg",
          },
          fcm_options: { link: `${SITE_DOMAIN}/needs/at/salisbury/` },
          data: { foodbank_slug: "salisbury", click_action: `${SITE_DOMAIN}/needs/at/salisbury/` },
        },
      },
    });
  });

  it("addresses the v1 send endpoint for the credential's own project, as the bearer of the minted token", async () => {
    await notify();

    const fcm = fcmCalls()[0]!;
    expect(fcm.url).toBe(`https://fcm.googleapis.com/v1/projects/${PROJECT_ID}/messages:send`);
    expect(fcm.method).toBe("POST");
    expect(fcm.headers).toEqual({ Authorization: `Bearer ${ACCESS_TOKEN}`, "Content-Type": "application/json" });
  });

  // The topic is the food bank's UUID, and the apps subscribe themselves to
  // it: get the topic wrong and the send succeeds, FCM reports a message
  // name, and not one phone is listening. There is no subscriber count to
  // notice the absence of, which is why this is asserted from the seeded
  // uuid rather than from the row the handler read.
  it("names the topic from the food bank's uuid, not its id or slug", async () => {
    await notify();

    const topic = (sentMessage().message as Record<string, unknown>).topic;
    expect(topic).toBe("foodbank-b0a1c2d3e4f5460788990a1b2c3d4e5f");
    // The two plausible wrong spellings, named rather than pattern-matched:
    // the uuid is hex, so "does not contain 7" would be false for the right
    // answer too.
    expect(topic).not.toBe("foodbank-salisbury");
    expect(topic).not.toBe(`foodbank-${SALISBURY_ID}`);
  });

  // FCM v1 REJECTS a non-string `data` value where the legacy API coerced
  // it. Both maps are string-valued today; this asserts it stays that way,
  // because a number slipped into either one is a 400 for every message.
  it("keeps every data value a string, as v1 requires", async () => {
    await notify();

    const msg = sentMessage().message as Record<string, Record<string, unknown>>;
    for (const value of Object.values(msg.data!)) expect(typeof value).toBe("string");
    for (const value of Object.values((msg.webpush!.data as Record<string, unknown>)!)) expect(typeof value).toBe("string");
  });

  // Django's own asymmetry, checked against all three call sites rather
  // than harmonised: the title uses foodbank.NAME (not full_name(), which
  // the email subject uses) and the RAW count (not apnumber()'s words). One
  // item really does read "needs 1 items".
  it("titles with the plain name and the raw count, ungrammatical singular included", async () => {
    db.prepare("UPDATE foodbankchange SET change_text = ? WHERE id = ?").run("Beans", NEED_ID);

    await notify();

    expect((sentMessage().message as Record<string, Record<string, string>>).notification!.title).toBe("Salisbury needs 1 items");
  });

  // The "Nothing" sentinel. no_items() special-cases it to 0 while
  // change_list() does not, so the notification reads "needs 0 items" with
  // the word "Nothing" as its body -- which is what Django sends today. The
  // admin only offers Notify on a need a human published, so this is a
  // reviewer's decision rather than a bug to paper over in the port.
  it("sends a 'Nothing' need as '0 items' with 'Nothing' as the body", async () => {
    db.prepare("UPDATE foodbankchange SET change_text = 'Nothing' WHERE id = ?").run(NEED_ID);

    await notify();

    expect((sentMessage().message as Record<string, Record<string, string>>).notification).toEqual({
      title: "Salisbury needs 0 items",
      body: "Nothing",
    });
  });

  // change_list() is the RAW split -- blank lines included. A need whose
  // text has a trailing newline notifies with a trailing ", " in the body,
  // and counts the blank as an item. Django does exactly this; pinned so
  // the port cannot quietly start filtering and diverge.
  it("keeps blank lines, in the count and in the body", async () => {
    db.prepare("UPDATE foodbankchange SET change_text = ? WHERE id = ?").run("Beans\n\nPasta\n", NEED_ID);

    await notify();

    expect((sentMessage().message as Record<string, Record<string, string>>).notification).toEqual({
      title: "Salisbury needs 4 items",
      body: "Beans, , Pasta, ",
    });
  });

  // notifications.py:220's 4,000-byte budget ("Firebase has a 4KB limit ...
  // we'll be conservative"). 45 items of 99 characters: 39 of them join to
  // 3,937 bytes and the 40th would make 4,038, so the body carries 39 while
  // the TITLE still says 45. That asymmetry is Django's too.
  it("truncates the body at 4,000 bytes, on an item boundary, leaving the count alone", async () => {
    const item = "A".repeat(99);
    db.prepare("UPDATE foodbankchange SET change_text = ? WHERE id = ?").run(Array(45).fill(item).join("\n"), NEED_ID);

    await notify();

    const notification = (sentMessage().message as Record<string, Record<string, string>>).notification!;
    expect(notification.title).toBe("Salisbury needs 45 items");
    expect(notification.body).toBe(Array(39).fill(item).join(", "));
    expect(new TextEncoder().encode(notification.body!).length).toBe(3937);
    // Whole items only -- never a half-written food item on somebody's
    // lock screen.
    expect(notification.body!.endsWith(item)).toBe(true);
  });

  // THE BUDGET IS INCLUSIVE, and 4,000 is the number. 87 items of 44
  // characters join to exactly 4,000 bytes, so this is the one fixture in
  // which `> budget` and `>= budget` disagree -- the second drops an item
  // that fits. It also pins the constant itself: at Firebase's real 4,096
  // the same text would carry 89 items, so a "the limit is 4KB, surely"
  // edit to notifications.py:220's deliberately conservative 4,000 shows up
  // here rather than as an occasional rejected message in production.
  it("keeps an item that lands exactly on the 4,000-byte budget", async () => {
    const item = "B".repeat(44);
    db.prepare("UPDATE foodbankchange SET change_text = ? WHERE id = ?").run(Array(90).fill(item).join("\n"), NEED_ID);

    await notify();

    const notification = (sentMessage().message as Record<string, Record<string, string>>).notification!;
    expect(notification.body).toBe(Array(87).fill(item).join(", "));
    expect(new TextEncoder().encode(notification.body!).length).toBe(4000);
  });

  // BYTES, NOT CHARACTERS, which is the one thing separating this builder
  // from the web push one (200 CHARACTERS). Two items of 1,000 "€" are
  // 2,002 characters -- comfortably inside 4,000 -- but 6,002 bytes, so
  // only the first survives. A char-counting mutant sends both and FCM
  // rejects the message outright.
  it("measures the budget in UTF-8 bytes, so multi-byte items count for more", async () => {
    const item = "€".repeat(1000);
    db.prepare("UPDATE foodbankchange SET change_text = ? WHERE id = ?").run(`${item}\n${item}`, NEED_ID);

    await notify();

    const notification = (sentMessage().message as Record<string, Record<string, string>>).notification!;
    expect(notification.body).toBe(item);
    expect(notification.body!.length).toBe(1000);
    expect(new TextEncoder().encode(notification.body!).length).toBe(3000);
  });

  // SUSPECT, pinned as-is. A single item bigger than the whole budget
  // leaves the body EMPTY -- the loop breaks before anything is kept -- and
  // the notification is sent anyway: a phone buzzes with "Salisbury needs 1
  // items" and no items. Django's loop has the same shape, so this is
  // ported behaviour rather than a port bug, and a 4,000-byte single line
  // is not something a reviewer would publish. Reported, not fixed.
  it("sends an empty body rather than nothing when the first item alone busts the budget", async () => {
    db.prepare("UPDATE foodbankchange SET change_text = ? WHERE id = ?").run("A".repeat(4001), NEED_ID);

    await notify();

    expect((sentMessage().message as Record<string, Record<string, string>>).notification).toEqual({
      title: "Salisbury needs 1 items",
      body: "",
    });
    expect(fcmCalls()).toHaveLength(1);
  });

  // STOPS at the first item that does not fit; it does not skip it and
  // carry on packing the shorter ones behind it. Django's loop breaks
  // ("Can't fit any more items", notifications.py:229-231) and the port
  // must too: a body that silently omitted item 12 while listing items 13
  // and 14 would look perfectly plausible on a phone and be a shopping
  // list nobody can act on. Every other truncation test here happens to
  // put the long items last, so this is the only fixture in which `break`
  // and `continue` differ at all.
  it("stops at the first item too big to fit rather than skipping it", async () => {
    db.prepare("UPDATE foodbankchange SET change_text = ? WHERE id = ?").run(`${"A".repeat(4001)}\nBeans`, NEED_ID);

    await notify();

    expect((sentMessage().message as Record<string, Record<string, string>>).notification).toEqual({
      title: "Salisbury needs 2 items",
      body: "",
    });
  });

  // The link is SITE_DOMAIN + the reversed wfbn:foodbank route. Concatenated
  // raw, so the binding must carry no trailing slash: this asserts the
  // shipped value's shape end to end rather than trusting the join.
  it("links to the food bank's own needs page on the configured domain", async () => {
    await notify();

    const webpush = (sentMessage().message as Record<string, Record<string, Record<string, string>>>).webpush!;
    expect(webpush.fcm_options!.link).toBe("https://www.givefood.org.uk/needs/at/salisbury/");
    expect(webpush.data!.click_action).toBe("https://www.givefood.org.uk/needs/at/salisbury/");
  });

  // ...and the domain comes from the BINDING. The fixture's SITE_DOMAIN is
  // the production one (workers/jobs/wrangler.jsonc:80), which makes
  // `${env.SITE_DOMAIN}` and a hard-coded "https://www.givefood.org.uk"
  // indistinguishable in every other assertion in this file -- that mutant
  // survived it. The second domain here is arbitrary; all that matters is
  // that it is not the one the rest of the file uses, so a baked-in domain
  // shows up as a link pointing at the wrong site rather than as nothing.
  it("takes the link's domain from the SITE_DOMAIN binding, not a baked-in one", async () => {
    await notify(NEED_ID, buildEnv({ SITE_DOMAIN: "https://gf-preview.example.test" }));

    const webpush = (sentMessage().message as Record<string, Record<string, Record<string, string>>>).webpush!;
    expect(webpush.fcm_options!.link).toBe("https://gf-preview.example.test/needs/at/salisbury/");
    expect(webpush.data!.click_action).toBe("https://gf-preview.example.test/needs/at/salisbury/");
  });

  // change_text is the PUBLISHED list; change_text_original is the uncleaned
  // text needcheck stored beside it, one column away in the same row. Every
  // need in this fixture carries a different one (ORIGINAL_TEXT), because
  // while that column was NULL a payload built from `need.change_text_original
  // ?? need.change_text` passed the whole file. The sibling email channel
  // guards the same confusion (needEmail.test.ts:801); it is a live enough
  // mistake in this schema to be worth guarding twice.
  it("notifies about the published change_text, not the uncleaned original beside it", async () => {
    expect(needRow(NEED_ID).change_text_original).toBe(ORIGINAL_TEXT);

    await notify();

    expect((sentMessage().message as Record<string, Record<string, string>>).notification).toEqual({
      title: "Salisbury needs 3 items",
      body: "Beans, Pasta, Tinned Tomatoes",
    });
  });

  // One HTTP call per NEED, not per subscriber: FCM addresses a topic and
  // the server holds no device list. mobilesubscriber exists in the schema
  // and is the analytics record the /mobsub/ endpoint writes -- treating it
  // as the send list would notify nobody, so this asserts the table is
  // never read.
  it("sends exactly one request and never reads the mobilesubscriber table", async () => {
    await notify();

    expect(fcmCalls()).toHaveLength(1);
    expect(prepared.map((p) => p.sql)).toEqual([
      "SELECT * FROM foodbankchange_full WHERE id = ?",
      "SELECT uuid, slug, name FROM foodbank WHERE id = ?",
    ]);
  });

  it("logs the message name FCM assigned, which is the only receipt this channel gets", async () => {
    fcmReply = () => okFcm("projects/givefood-test/messages/0:1757332800000000%deadbeef");

    await notify();

    expect(consoleLog).toHaveBeenCalledWith(
      `notify-need-firebase: sent need ${NEED_ID} to topic foodbank-${SALISBURY_UUID}: projects/givefood-test/messages/0:1757332800000000%deadbeef`,
    );
    expect(consoleError).not.toHaveBeenCalled();
  });

  it("says (no name) when the success response carries no message name", async () => {
    fcmReply = () => new Response("{}", { status: 200 });

    await notify();

    expect(consoleLog).toHaveBeenCalledWith(
      `notify-need-firebase: sent need ${NEED_ID} to topic foodbank-${SALISBURY_UUID}: (no name)`,
    );
  });
});

