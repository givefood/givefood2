// The D1DatabaseSession surface packages/db uses, over node:sqlite -- the
// same shim shape as packages/db/src/notifySubscribers.test.ts's.
// Deliberately dumb: it forwards the SQL untouched so the ENGINE decides
// which row comes back, rather than this file re-implementing SQLite and
// then agreeing with itself.
function d1Session() {
  const statement = (sql: string, params: Bindable[]) => ({
    bind: (...next: unknown[]) => statement(sql, next as Bindable[]),
    first: async <T>() => {
      prepared.push({ sql, params });
      return (db.prepare(sql).get(...params) as T | undefined) ?? null;
    },
    all: async () => {
      prepared.push({ sql, params });
      return { results: db.prepare(sql).all(...params), success: true, meta: {} };
    },
    run: async () => {
      prepared.push({ sql, params });
      const info = db.prepare(sql).run(...params);
      return { success: true, meta: { changes: Number(info.changes), last_row_id: Number(info.lastInsertRowid) } };
    },
  });
  return { prepare: (sql: string) => statement(sql, []), getBookmark: () => null };
}

