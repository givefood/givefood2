// The ack/retry decision is not made in needFirebase.ts -- it is made in
// queues/jobs.ts, which acks on return and retries on throw. Since every
// failure above returns, EVERY firebase failure is acked. Asserting that
// through the REAL handleJobsQueue rather than by reasoning about it is the
// point: the "jobs" queue is configured max_retries 3 with a jobs-dlq
// (workers/jobs/wrangler.jsonc:149-152), so "acks" means a broken Firebase
// credential produces an EMPTY dead-letter queue while every app
// notification stops. That is the invisible-failure shape this whole file
// is about, and it is deliberate: Django's send_firebase_notification
// swallows its exceptions the same way.
describe("through the real jobs consumer -- what actually gets acked", () => {
  interface FakeMessage {
    body: unknown;
    ack: () => void;
    retry: () => void;
  }

  function fakeBatch(bodies: unknown[]) {
    const acked: number[] = [];
    const retried: number[] = [];
    const messages: FakeMessage[] = bodies.map((body, index) => ({
      body,
      ack: () => void acked.push(index),
      retry: () => void retried.push(index),
    }));
    const batch = { queue: "jobs", messages } as unknown as Parameters<typeof handleJobsQueue>[0];
    return { batch, acked, retried };
  }

  it("routes a notify-need-firebase message to this handler and acks it", async () => {
    const { batch, acked, retried } = fakeBatch([message()]);

    await handleJobsQueue(batch, buildEnv());

    expect(fcmCalls()).toHaveLength(1);
    expect(acked).toEqual([0]);
    expect(retried).toEqual([]);
  });

  it("acks a message whose FCM send was refused, so nothing ever reaches jobs-dlq", async () => {
    fcmReply = () => new Response("no", { status: 500 });
    const { batch, acked, retried } = fakeBatch([message()]);

    await handleJobsQueue(batch, buildEnv());

    expect(acked).toEqual([0]);
    expect(retried).toEqual([]);
    expect(consoleError).toHaveBeenCalledWith(expect.stringContaining("notify-need-firebase: FCM 500"));
  });

  it("acks a message for a need that no longer exists", async () => {
    const { batch, acked, retried } = fakeBatch([message(4242)]);

    await handleJobsQueue(batch, buildEnv());

    expect(acked).toEqual([0]);
    expect(retried).toEqual([]);
  });

  it("acks a message whose credential is missing, leaving only the warning", async () => {
    const { batch, acked, retried } = fakeBatch([message()]);

    await handleJobsQueue(batch, buildEnv({ FIREBASE_SERVICE_ACCOUNT: undefined }));

    expect(acked).toEqual([0]);
    expect(retried).toEqual([]);
    expect(consoleWarn).toHaveBeenCalledTimes(1);
  });

  // THE MALFORMED MESSAGE. queues/jobs.ts:70 casts the body without
  // validating it, so a message with no needId reaches getNeedById with
  // `undefined` and the DRIVER rejects the bind -- there is no guard in
  // this handler for it. That throws out of the handler, which is the one
  // path that does NOT ack: three retries and then jobs-dlq, which is the
  // right destination for a message no amount of retrying will fix.
  //
  // The error object here is node:sqlite's TypeError, because that is what
  // this harness's session is built on; D1 raises its own type error for an
  // undefined bind. Not verified against a live D1 -- what is asserted, and
  // all that matters to the queue, is that the handler does not swallow it.
  it("lets a message with no needId throw, so it retries rather than being acked", async () => {
    const { batch, acked, retried } = fakeBatch([{ type: "notify-need-firebase" }]);

    await handleJobsQueue(batch, buildEnv());

    expect(retried).toEqual([0]);
    expect(acked).toEqual([]);
    expect(calls).toEqual([]);
  });

  // SUSPECT, pinned as-is: the ONE credential shape that does not ack.
  // parseServiceAccount's try wraps only the JSON.parse, so a credential
  // whose text is `null` parses cleanly to null and is dereferenced on the
  // very next line -- a TypeError out of the handler, three retries, and a
  // jobs-dlq entry, where every other broken credential in this file warns
  // or logs once and acks. Nobody sets a secret to "null" deliberately; what
  // this pins is that the module's stated contract ("a missing credential is
  // a warning and a return, not an error") has exactly one hole in it, and
  // that the hole is in the direction of a retry rather than a silent ack.
  // Reported, not fixed.
  it("retries rather than acks when the credential parses to null", async () => {
    const { batch, acked, retried } = fakeBatch([message()]);

    await handleJobsQueue(batch, buildEnv({ FIREBASE_SERVICE_ACCOUNT: "null" }));

    expect(retried).toEqual([0]);
    expect(acked).toEqual([]);
    expect(consoleError).toHaveBeenCalledWith(
      'givefood2-jobs: "jobs" message failed',
      { type: "notify-need-firebase", needId: NEED_ID },
      expect.any(TypeError),
    );
    // Not even the database was touched, so the retries are free apart from
    // the queue's own delivery.
    expect(calls).toEqual([]);
    expect(prepared).toEqual([]);
  });

  // A batch is up to ten messages (wrangler.jsonc:149) and the notify fan-out
  // sends four at a time, so several firebase messages in one batch is the
  // normal case rather than the exotic one. One failing message must not
  // cost the others their send -- and the cached token means the batch
  // costs one exchange, not one per message.
  it("keeps sending the rest of the batch when one message's need is gone", async () => {
    const { batch, acked, retried } = fakeBatch([message(4242), message(NEED_ID), message(DECOY_NEED_ID)]);

    await handleJobsQueue(batch, buildEnv());

    expect(acked).toEqual([0, 1, 2]);
    expect(retried).toEqual([]);
    expect(tokenCalls()).toHaveLength(1);
    expect(fcmCalls().map((c) => (JSON.parse(c.body) as { message: { topic: string } }).message.topic)).toEqual([
      `foodbank-${SALISBURY_UUID}`,
      `foodbank-${DEVIZES_UUID}`,
    ]);
  });
});
