type Bindable = null | number | bigint | string | Uint8Array;

interface Prepared {
  sql: string;
  params: Bindable[];
}

let db: DatabaseSync;
/** Every statement this handler actually ran, in order, with its binds. */
let prepared: Prepared[];
/** The bookmark mode each withSession() was asked for. */
