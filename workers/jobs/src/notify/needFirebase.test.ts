/** The service-account assertion out of the token request's form body. */
function assertionOf(index = 0): string {
  return new URLSearchParams(tokenCalls()[index]!.body).get("assertion")!;
}

// base64url decoded WITHOUT the module's own jwt.ts helpers. Decoding with
// the same code that encoded would agree with an encoder that had, say,
// forgotten the +/- substitution -- and Google would not.
function segmentBytes(segment: string): Uint8Array {
  const b64 = segment.replace(/-/g, "+").replace(/_/g, "/");
  const binary = atob(b64.padEnd(Math.ceil(b64.length / 4) * 4, "="));
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return bytes;
}

function segmentJson(segment: string): Record<string, unknown> {
  return JSON.parse(new TextDecoder().decode(segmentBytes(segment))) as Record<string, unknown>;
}

