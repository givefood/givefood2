describe("the service-account credential -- the failure that is invisible by construction", () => {
  // notifications.py:170-172 warns and returns rather than raising, because
  // the other three channels are separate tasks and must still go out. The
  // level matters and is asserted: a Worker's logs are filtered by level, and
  // demoting this to console.log would remove the only trace that anything
  // was skipped.
  it("warns and does nothing at all when FIREBASE_SERVICE_ACCOUNT is unset", async () => {
    await expect(notify(NEED_ID, buildEnv({ FIREBASE_SERVICE_ACCOUNT: undefined }))).resolves.toBeUndefined();

    expect(consoleWarn).toHaveBeenCalledWith("notify-need-firebase: FIREBASE_SERVICE_ACCOUNT not set, skipping");
    expect(consoleError).not.toHaveBeenCalled();
    // No round trip, and no DATABASE round trip either: the credential check
    // is first, so a Worker deployed without the secret costs nothing per
    // message beyond the log line.
    expect(calls).toEqual([]);
    expect(prepared).toEqual([]);
  });

  // A secret that exists but is empty is what `wrangler secret put` leaves
  // behind when someone pipes it an empty file, and the guard is truthiness
  // rather than `=== undefined`, so this must take the same branch. If it
  // ever fell through instead, JSON.parse("") would raise a SyntaxError --
  // caught, but reported as "not valid JSON", which sends an operator
  // looking for a malformed secret rather than a missing one.
  it("treats an empty-string credential as unset, not as malformed JSON", async () => {
    await notify(NEED_ID, buildEnv({ FIREBASE_SERVICE_ACCOUNT: "" }));

    expect(consoleWarn).toHaveBeenCalledWith("notify-need-firebase: FIREBASE_SERVICE_ACCOUNT not set, skipping");
    expect(consoleError).not.toHaveBeenCalled();
    expect(calls).toEqual([]);
  });

  // notifications.py:174-177's json.JSONDecodeError branch, same non-fatal
  // shape. Returning normally is the load-bearing half: it means the queue
  // ACKS a message whose credential is unusable, so nothing accumulates in
  // jobs-dlq for anyone to notice.
  it("logs and returns for a credential that is not JSON", async () => {
    await expect(notify(NEED_ID, buildEnv({ FIREBASE_SERVICE_ACCOUNT: "{not json" }))).resolves.toBeUndefined();

    expect(consoleError).toHaveBeenCalledWith("notify-need-firebase: FIREBASE_SERVICE_ACCOUNT is not valid JSON");
    // ONE line, and it is that one. A mutant that logged this and then fell
    // through to the shape check added "is missing project_id/client_email/
    // private_key" underneath it, which is both false and actively
    // misleading -- it sends an operator looking for a truncated credential
    // rather than an unparseable one. For a channel whose entire
    // operator-visible surface is a log line, a second contradictory line is
    // the whole bug, and toHaveBeenCalledWith alone could not see it.
    expect(consoleError).toHaveBeenCalledTimes(1);
    expect(calls).toEqual([]);
    expect(prepared).toEqual([]);
  });

  // Valid JSON of the wrong shape -- what pasting the OAuth client secret,
  // or a truncated file, actually produces. Each field is checked
  // separately because the three are checked in one `if` and a dropped
  // clause is invisible unless the field it guards is missing on its own.
  for (const field of ["project_id", "client_email", "private_key"] as const) {
    it(`logs and returns when the credential has no ${field}`, async () => {
      await notify(NEED_ID, buildEnv({ FIREBASE_SERVICE_ACCOUNT: serviceAccount({ [field]: undefined }) }));

      expect(consoleError).toHaveBeenCalledWith(
        "notify-need-firebase: FIREBASE_SERVICE_ACCOUNT is missing project_id/client_email/private_key",
      );
      expect(calls).toEqual([]);
    });

    // The same guard reached through the other falsy spelling. An empty
    // project_id would otherwise POST to
    // `https://fcm.googleapis.com/v1/projects//messages:send`, which is a
    // 404 from Google and one more error log nobody reads.
    it(`treats an empty-string ${field} as missing`, async () => {
      await notify(NEED_ID, buildEnv({ FIREBASE_SERVICE_ACCOUNT: serviceAccount({ [field]: "" }) }));

      expect(consoleError).toHaveBeenCalledWith(
        "notify-need-firebase: FIREBASE_SERVICE_ACCOUNT is missing project_id/client_email/private_key",
      );
      expect(calls).toEqual([]);
    });
  }

  // A whole JSON blob with the right keys but a private_key that is not a
  // PKCS#8 RSA key -- a re-wrapped or truncated secret, which is exactly
  // what a credential rotation gone wrong looks like. importRs256Key throws
  // and the error is caught: NO fetch at all, not even the token exchange.
  it("logs and returns when the private key cannot be imported, without any round trip", async () => {
    const broken = serviceAccount({ private_key: "-----BEGIN PRIVATE KEY-----\nbm90LWEta2V5\n-----END PRIVATE KEY-----\n" });

    await expect(notify(NEED_ID, buildEnv({ FIREBASE_SERVICE_ACCOUNT: broken }))).resolves.toBeUndefined();

    expect(consoleError).toHaveBeenCalledWith(
      "notify-need-firebase: could not sign the service-account assertion",
      expect.any(Error),
    );
    expect(calls).toEqual([]);
  });
});

