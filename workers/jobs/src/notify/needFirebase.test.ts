describe("the OAuth2 token exchange -- what firebase-admin's credential layer does for Django", () => {
  it("POSTs the JWT-bearer grant, form-encoded, to Google's token endpoint before touching FCM", async () => {
    await notify();

    expect(calls.map((c) => c.url)).toEqual([TOKEN_URL, `${FCM_PREFIX}${PROJECT_ID}/messages:send`]);
    const token = tokenCalls()[0]!;
    expect(token.method).toBe("POST");
    expect(token.headers).toEqual({ "Content-Type": "application/x-www-form-urlencoded" });
    // urn:ietf:params:oauth:grant-type:jwt-bearer, RFC 7523 §2.1. Anything
    // else is a 400 from Google, and this handler's only response to a 400
    // is a log line.
    const form = new URLSearchParams(token.body);
    expect(form.get("grant_type")).toBe("urn:ietf:params:oauth:grant-type:jwt-bearer");
    expect(form.get("assertion")).toBeTruthy();
    expect([...form.keys()].sort()).toEqual(["assertion", "grant_type"]);
  });

  // THE ASSERTION IS THE CREDENTIAL. Every claim here is one Google
  // validates and rejects the whole exchange over, and a rejection reaches
  // production as a console.error and nothing else.
  it("signs an RS256 assertion whose claims are the ones Google validates", async () => {
    await notify();

    const [header, claims] = assertionOf().split(".");
    expect(segmentJson(header!)).toEqual({ alg: "RS256", typ: "JWT" });
    expect(segmentJson(claims!)).toEqual({
      iss: CLIENT_EMAIL,
      scope: "https://www.googleapis.com/auth/firebase.messaging",
      // `aud` is the TOKEN ENDPOINT, not the FCM API: the assertion is
      // addressed to whoever exchanges it. Naming fcm.googleapis.com here
      // is a plausible edit and an invalid_grant from Google.
      aud: TOKEN_URL,
      iat: NOW_SEC,
      exp: NOW_SEC + 3600,
    });
  });

  // `iat` is FLOORED, not rounded. The fixture clock is .750 of a second
  // past the tick precisely so that a Math.round() here would produce an
  // iat one second in the FUTURE, which Google rejects as
  // "Invalid JWT: Token must be a short-lived token".
  it("floors iat to the second rather than rounding it", async () => {
    await notify();

    const claims = segmentJson(assertionOf().split(".")[1]!);
    expect(claims.iat).toBe(NOW_SEC);
    // The guard on the guard: if the fixture clock ever became a whole
    // number of seconds, the assertion above would stop proving anything.
    expect(NOW_SEC * 1000).not.toBe(NOW);
  });

  // A real signature check with the real public half of the real key.
  // "An assertion was sent" and "an assertion Google will accept" are
  // different claims, and only the second one keeps notifications flowing.
  it("signs the assertion with the service account's own key", async () => {
    await notify();

    const assertion = assertionOf();
    const signature = segmentBytes(assertion.split(".")[2]!);
    const signed = new TextEncoder().encode(assertion.slice(0, assertion.lastIndexOf(".")));

    await expect(
      crypto.subtle.verify(
        "RSASSA-PKCS1-v1_5",
        PUBLIC_KEY,
        signature as unknown as ArrayBuffer,
        signed as unknown as ArrayBuffer,
      ),
    ).resolves.toBe(true);
  });

  // base64URL, not base64: a "+", "/" or "=" in any segment makes the JWT
  // unparseable to Google. jwt.ts does the substitution and the strip, and
  // this is the assertion that says so without going through jwt.ts's own
  // decoder to find out.
  it("emits base64url segments with no padding", async () => {
    await notify();

    expect(assertionOf()).toMatch(/^[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+$/);
  });

  // Service-account JSON may carry its own token_uri (Google has issued
  // more than one over the years, and an emulator sets its own). The
  // override has to move BOTH the request and the `aud` claim -- moving
  // only the request produces an assertion the new endpoint rejects.
  it("honours a token_uri in the credential, in the request and in aud alike", async () => {
    await notify(NEED_ID, buildEnv({ FIREBASE_SERVICE_ACCOUNT: serviceAccount({ token_uri: ALTERNATE_TOKEN_URL }) }));

    expect(tokenCalls()[0]!.url).toBe(ALTERNATE_TOKEN_URL);
    expect(segmentJson(assertionOf().split(".")[1]!).aud).toBe(ALTERNATE_TOKEN_URL);
    expect(fcmCalls()).toHaveLength(1);
  });

  // Both outbound calls carry an AbortSignal. A hung connection to Google
  // would otherwise hold the message for the consumer's whole timeout and
  // take the batch's other nine messages down with it.
  it("bounds both outbound calls with a timeout: 15s on the exchange, 20s on the send", async () => {
    await notify();

    expect(calls.map((c) => c.aborts)).toEqual([true, true]);
    // THE VALUES, not merely their presence. With only the booleans above,
    // two plausible careless edits survived this entire file: swapping the
    // two durations (20s on the exchange, 15s on the send), and cutting the
    // send's to 20ms -- which would abort every notification the moment FCM
    // was fractionally slow, and report it as "send failed" with no status.
    expect(timeoutsMs).toEqual([15_000, 20_000]);
  });
});

describe("the token cache -- one RSA signature and one round trip per hour, not per message", () => {
  // firebase-admin caches the same way (its initialize_app is guarded by
  // get_app()). Minting per message would add an RSA signature and a round
  // trip to Google to every notification for no benefit.
  it("mints once and reuses the token for the next message in the same isolate", async () => {
    await notify(NEED_ID);
    await notify(DECOY_NEED_ID);

    expect(tokenCalls()).toHaveLength(1);
    expect(fcmCalls()).toHaveLength(2);
    expect(fcmCalls()[1]!.headers.Authorization).toBe(`Bearer ${ACCESS_TOKEN}`);
  });

  // The 60 seconds of slack the module's comment claims, asserted at both
  // sides of the boundary. A token used one second past its life is a 401
  // from FCM, which this handler reports as a log line and nothing else --
  // so the slack is the difference between a refreshed token and an hour of
  // silently dropped notifications.
  it("reuses the token right up to expires_in minus 60 seconds", async () => {
    await notify();
    vi.setSystemTime(NOW + 3600_000 - 60_000 - 1);
    await notify();

    expect(tokenCalls()).toHaveLength(1);
  });

  it("re-mints the moment the 60-second slack is reached", async () => {
    await notify();
    tokenReply = () => okToken({ access_token: "ya29.a0AfB_second-token" });
    vi.setSystemTime(NOW + 3600_000 - 60_000);
    await notify();

    expect(tokenCalls()).toHaveLength(2);
    expect(fcmCalls()[1]!.headers.Authorization).toBe("Bearer ya29.a0AfB_second-token");
  });

  // Google always sends expires_in, but the `?? 3600` is the difference
  // between a sane default and `NaN`: `nowMs + (undefined - 60) * 1000` is
  // NaN, and `NaN > nowMs` is false, so a missing default would silently
  // turn the cache off and mint per message.
  it("falls back to an hour when the response omits expires_in", async () => {
    tokenReply = () => new Response(JSON.stringify({ access_token: ACCESS_TOKEN }), { status: 200 });

    await notify();
    vi.setSystemTime(NOW + 3600_000 - 60_000 - 1);
    await notify();

    expect(tokenCalls()).toHaveLength(1);
  });

  // A token shorter-lived than the slack caches as ALREADY EXPIRED, so the
  // next message mints again rather than reusing something Google would
  // reject. Degenerate, but it is the arithmetic's edge and it degrades the
  // safe way.
  it("never reuses a token whose lifetime is shorter than the slack", async () => {
    tokenReply = () => okToken({ expires_in: 30 });

    await notify(NEED_ID);
    await notify(DECOY_NEED_ID);

    expect(tokenCalls()).toHaveLength(2);
  });

  // A failed exchange must not poison the cache: `cachedToken` is assigned
  // only on the success path. If a transient 503 cached a null token, every
  // subsequent message in that isolate would send `Bearer null` and FCM
  // would 401 them all -- an hour of silence from one bad second.
  it("does not cache anything when the exchange fails, and recovers on the next message", async () => {
    tokenReply = () => new Response(JSON.stringify({ error: "internal_failure" }), { status: 503 });

    await notify(NEED_ID);
    expect(fcmCalls()).toEqual([]);

    tokenReply = () => okToken();
    await notify(DECOY_NEED_ID);

    expect(tokenCalls()).toHaveLength(2);
    expect(fcmCalls()).toHaveLength(1);
    expect(fcmCalls()[0]!.headers.Authorization).toBe(`Bearer ${ACCESS_TOKEN}`);
  });

  // SUSPECT, pinned as-is. The cache is "keyed by nothing" -- the module
  // says so, on the grounds that one Worker has one service account. That
  // holds today, but it means a redeployed Worker whose secret was rotated
  // mid-isolate keeps signing with the OLD project's token while addressing
  // the NEW project's URL: the second account here has a private key that
  // cannot even be imported, and no signing is attempted because the token
  // is already in hand. FCM answers 403 and the only symptom is a log line.
  // Reported, not fixed.
  it("reuses a cached token even after the credential itself changes", async () => {
    await notify(NEED_ID);

    const rotated = serviceAccount({
      project_id: "givefood-rotated",
      private_key: "-----BEGIN PRIVATE KEY-----\nbm90LWEta2V5\n-----END PRIVATE KEY-----\n",
    });
    await notify(DECOY_NEED_ID, buildEnv({ FIREBASE_SERVICE_ACCOUNT: rotated }));

    expect(tokenCalls()).toHaveLength(1);
    expect(fcmCalls()[1]!.url).toBe(`${FCM_PREFIX}givefood-rotated/messages:send`);
    expect(fcmCalls()[1]!.headers.Authorization).toBe(`Bearer ${ACCESS_TOKEN}`);
  });
});

describe("when the token exchange fails", () => {
  // The exact shape of the credential outage this file exists for: three
  // arguments, so an operator grepping the logs gets Google's own reason
  // ("invalid_grant", "Invalid JWT Signature") rather than just a status.
  it("logs the status and Google's own reason, and does not call FCM", async () => {
    tokenReply = () =>
      new Response(JSON.stringify({ error: "invalid_grant", error_description: "Invalid JWT Signature." }), { status: 400 });

    await expect(notify()).resolves.toBeUndefined();

    expect(consoleError).toHaveBeenCalledWith(
      "notify-need-firebase: token exchange failed (HTTP 400)",
      "invalid_grant",
      "Invalid JWT Signature.",
    );
    expect(fcmCalls()).toEqual([]);
    expect(consoleLog).not.toHaveBeenCalled();
  });

  // A 200 with no access_token in it. `!res.ok || !payload.access_token` is
  // one condition; dropping the second half would send `Bearer undefined`
  // to FCM and turn a clean failure into a 401 per message.
  it("treats a 200 with no access_token as a failure", async () => {
    tokenReply = () => new Response(JSON.stringify({ token_type: "Bearer", expires_in: 3600 }), { status: 200 });

    await notify();

    expect(consoleError).toHaveBeenCalledWith(
      "notify-need-firebase: token exchange failed (HTTP 200)",
      undefined,
      undefined,
    );
    expect(fcmCalls()).toEqual([]);
  });

  // The STATUS is load-bearing on its own. `!res.ok || !payload.access_token`
  // is one condition and the file used to assert only the second half of it,
  // so narrowing the check to `!payload.access_token` -- a tidy-looking edit,
  // since the token is what the function returns -- survived every test here.
  // What it costs: a token minted from an ERROR response is cached for an
  // hour and presented to FCM, which 401s every message in the isolate. The
  // body below is not something Google sends; it is the smallest input that
  // makes the two halves of that condition distinguishable, and the
  // assertions are what the shipped code does with it today.
  it("treats an error status as a failure even when the body carries an access_token", async () => {
    tokenReply = () =>
      new Response(JSON.stringify({ access_token: ACCESS_TOKEN, expires_in: 3600 }), { status: 503 });

    await notify(NEED_ID);

    expect(consoleError).toHaveBeenCalledWith(
      "notify-need-firebase: token exchange failed (HTTP 503)",
      undefined,
      undefined,
    );
    expect(fcmCalls()).toEqual([]);
    // And nothing was cached from it: the next message mints again rather
    // than presenting a token the exchange never actually granted.
    tokenReply = () => okToken();
    await notify(DECOY_NEED_ID);
    expect(tokenCalls()).toHaveLength(2);
    expect(fcmCalls()[0]!.headers.Authorization).toBe(`Bearer ${ACCESS_TOKEN}`);
  });

  it("logs and returns when Google cannot be reached at all", async () => {
    tokenReply = () => {
      throw new TypeError("Network connection lost.");
    };

    await expect(notify()).resolves.toBeUndefined();

    expect(consoleError).toHaveBeenCalledWith("notify-need-firebase: token exchange could not be reached", expect.any(TypeError));
    expect(fcmCalls()).toEqual([]);
  });

  // SUSPECT, pinned as-is. `res.json()` is awaited BEFORE `res.ok` is
  // consulted, so an error page that is not JSON -- a proxy's HTML 502, a
  // captive portal -- is reported as "could not be reached" and the HTTP
  // status never appears in the logs at all. The handling is otherwise
  // identical (log, return, ack), so this costs diagnosis rather than
  // behaviour. Reported, not fixed.
  it("reports a non-JSON error page as unreachable, losing the status code", async () => {
    tokenReply = () => new Response("<html><body>502 Bad Gateway</body></html>", { status: 502 });

    await notify();

    expect(consoleError).toHaveBeenCalledWith("notify-need-firebase: token exchange could not be reached", expect.any(Error));
    expect(consoleError).not.toHaveBeenCalledWith(
      expect.stringContaining("token exchange failed"),
      expect.anything(),
      expect.anything(),
    );
    expect(fcmCalls()).toEqual([]);
  });
});

