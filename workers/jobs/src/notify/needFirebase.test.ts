describe("the database is only ever read", () => {
  // The `notified` stamp is the PRODUCER's business (routes/admin/needs.ts
  // writes it before enqueuing all four channels). If this consumer ever
  // started writing, an at-least-once redelivery would rewrite it, and a
  // failed send would leave a need looking notified. Reading the row back
  // is the assertion; a green status from the handler is not.
  it("leaves the need row byte-identical after a successful send", async () => {
    const before = needRow(NEED_ID);

    await notify();

    expect(needRow(NEED_ID)).toEqual(before);
    expect(before.notified).toBeNull();
  });

  // Every statement, not just the ones with obvious side effects: a shared
  // packages/db helper that grew a write would land here silently.
  it("runs nothing but SELECTs", async () => {
    await notify();

    for (const statement of prepared) expect(statement.sql.trimStart().slice(0, 6).toUpperCase()).toBe("SELECT");
  });
});

describe("at-least-once delivery -- Cloudflare Queues can deliver the same tick twice", () => {
  // NOT IDEMPOTENT, BY DESIGN, and the design is stated in the module's own
  // header: "A notification is worth sending once, at the moment the
  // reviewer pressed the button". There is no dedup key and no stamp, so a
  // redelivered message really does buzz every subscribed phone a second
  // time. Pinned so that the absence of a guard is a decision on record
  // rather than an oversight -- and so that anyone adding one has to change
  // this test deliberately.
  it("sends again on a redelivered message, with no dedup and no stamp", async () => {
    await notify();
    await notify();

    expect(fcmCalls()).toHaveLength(2);
    expect(fcmCalls()[0]!.body).toBe(fcmCalls()[1]!.body);
    // One mint, two sends: the cache absorbs the duplicate's cost.
    expect(tokenCalls()).toHaveLength(1);
    expect(needRow(NEED_ID).notified).toBeNull();
  });
});

